"""L1 环境槽的正文。

**为什么环境要进上下文。** 没有它，模型不知道"现在几点"——而"明天提醒我"、
"这周还剩几天"这类话全都要靠今天是什么日子。这是最小的一层：几行字，但每一轮
都要有。

**为什么不用模型自己的时间感知。** 它没有。4B 模型的训练数据截止在某一天，而它
会拿那个日期当"今天"。一句"现在是 2026-10-10 星期六 15:04"能挡掉整类错得理直气壮
的回答，代价是十几个 token。

**这里只写事实，不写指令。** 指令属于人格锚（L0）——两处都写会让人格锚的"一个字
都不许改写"这条纪律变得没有意义：模型读到的行为约束就成了两处的并集，而改人格锚
不一定改得动行为。

那条纪律决定了下面两个"这一轮"的槽怎么写：写的是**能力**（"这一轮没有工具"），
不是**要求**（"不要声称你调用了工具"）。差别不是修辞——前者是模型无法自己知道的
事实，后者是一条行为约束。

**"不许声称你调用了工具"落在 L0**（它是一条要求，理由同上），这一层只管"这一轮有
没有工具"这个事实。这一层仍然要更小心地写，因为**它才是每轮都在场的那一句**：人格锚
给了"只说你真的做过的事"这条通则，而具体到这一轮发生了什么，只有这里知道。

所以这里只留一句**事件**："也不会有任何动作被执行"。2026-10-11 实测过列清单的代价：
用户打「晚上好」，模型把清单原样背了回去（"我无法使用工具查看记忆"），用户于是以为
工具坏了。事件句背出来的是这一轮**发生了什么**，不是一条能力免责声明——里面已经没有
能力可列。
"""

from __future__ import annotations

from datetime import datetime

__all__ = ["build_environment"]

_WEEKDAYS = ("星期一", "星期二", "星期三", "星期四", "星期五", "星期六", "星期日")


def build_environment(
    *,
    model_id: str = "",
    now: datetime | None = None,
    tools_declared: bool = True,
    needs_clarification: bool = False,
    speech_receipt: str = "",
) -> str:
    """拼 L1 的正文。

    Args:
        model_id: 当前后端的稳定标识（``ollama/qwen3-4b``）。写进上下文是为了让
            模型知道**它现在是谁**——同一个记忆库会被不同的模型读到，而"换模型 =
            换读者"这件事在界面上看得到、在上下文里也该看得到。测试与命令行传空串。
        now: 当前时间。可注入是为了让这行文本可复现——它每轮都进上下文，一个跟着
            真实时钟变的值会让"同样的输入给出同样的请求"这条断言写不出来。
        tools_declared: 这一轮有没有把工具声明给模型（见
            :attr:`~axo.agent.router.RoutedTurn.uses_tools`）。
            **为假时补一句"这一轮不会有任何动作被执行"。** 默认 ``True`` 意味着
            "不表态"——老调用方与既有测试的输出逐字节不变。
        needs_clarification: 这一轮的路由判不准用户是想闲聊还是要做事
            （:attr:`~axo.agent.router.RoutedTurn.wants_clarification`）。

    Returns:
        两三行文本。**空输入给空串**（没给模型标识也照样给时间）。

    为什么 ``tools_declared`` 要进上下文：**模型没法自己知道这件事。** 工具是靠
    请求里的 ``tools`` 字段声明的（``llm/base.py``），而"字段不存在"与"字段为空"
    在模型的输入里长得一模一样——它只读得到自己收到了什么，读不到自己**没**收到
    什么。2026-10-10 的实测就是这个形状：一轮闲聊语域里用户说"记住：我最喜欢靛蓝"，
    模型回"已通过 write_memory 工具保存"——那一轮请求里根本没有 ``tools``。它凭空
    报了一个自己做不到的动作，而界面上看不出来（那正是"真相在逐字稿里，不在模型的
    自述里"这条纪律要挡的东西）。
    """
    moment = now or datetime.now()
    lines = [
        f"当前时间：{moment.strftime('%Y-%m-%d')} {_WEEKDAYS[moment.weekday()]}"
        f" {moment.strftime('%H:%M')}。"
    ]
    if model_id:
        lines.append(f"你此刻由 {model_id} 驱动；记忆不属于你，属于这台机器。")
    if needs_clarification:
        lines.append("这一句是闲聊还是要做一件具体的事，没判准。")
    if not tools_declared:
        # 一句**事件**，不是一句"我做不到"。也**不列清单**——清单会被原样背成
        # 能力免责声明，两件事的现场都在模块文档里。
        lines.append("这一轮没有工具可用，也不会有任何动作被执行。")
    if speech_receipt:
        # 播出回执（``tts.SpeechReceipt.describe`` 的产物）。**用完即清**（调用方
        # 拿走即抹）：这是一条关于「刚说的那句出没出声」的信号，不是常驻状态。
        # 带时间戳、失败带原因——见 ``tts.SpeechReceipt`` 那三条要求。
        lines.append(speech_receipt)
    return "\n".join(lines)
