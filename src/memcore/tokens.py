"""token 数的估算。

**为什么要估而不是算**：:class:`axo.llm.base.ChatBackend` 的
``count_tokens`` 对本机后端返回 ``None``——Ollama 在发请求前没有廉价的分词端点。
而装配预算必须在**发请求之前**就把每一条候选算清楚，所以只能估。

**系数是量出来的，不是猜的。** 本机（Ollama 0.40.2 + Qwen3-4B）实测：把文本作为
单独一条 user 消息发给 ``/api/chat``，读 ``prompt_eval_count``，扣掉整轮对话的固定
底价 **12**（消息包装 5 + 生成提示 7），就是这段文本自己的 token 数。

第一轮用 18 条真实混合样本量，结果是**系统性低估**：中位 0.88、最差 0.45、13/18
偏低。病根在第二轮的分档量里看清楚了::

    汉字        0.556   0.667   0.654      （18/18/26 字）
    数字        1.000   1.000   1.000      ← 一个数字就是一个 token
    英文散文    0.156   0.167   0.200
    路径与标识符 0.231   0.327   0.329
    中文标点    0.500   1.000   1.000      （同样的「，」，在两个样本里差一倍）
    ASCII 标点  0.031   0.613   0.125      （32 个连字符 = 1 个 token）

同一个类别内部就能差 32 倍（标点），所以**没法用一个系数盖住所有字符**。旧实现把
数字和字母并进同一个 0.24 的桶，这正是最差那两个样本（0.45、0.57）的来源——
``配置项 num_ctx 的值是 16384`` 这种句子有一半的 token 花在数字上。

于是按**测量到的上沿**分档取值，宁可高估：

===========  ==================  ==============================
类别         取值                实测上沿
===========  ==================  ==============================
汉字         0.70                0.667
数字         1.00                1.000
拉丁字母     0.35                0.329（散文只有 0.20，见下）
其他         1.00                1.000
===========  ==================  ==============================

第三轮把新旧系数放在同一批 20 条样本上比（后两条是刻意加的 Markdown 与代码块）::

    旧：最小 0.45  中位 0.88  最大 1.73  低估 14/20
    新：最小 0.91  中位 1.04  最大 5.33  低估  5/20

**已知的两处偏差，都是刻意选的**：

* 纯中文被高估约 10~15%，纯英文散文被高估约一倍（实测只有 0.156~0.200，取 0.35
  是为了盖住同属"拉丁字母"的标识符与路径）。本项目中文优先，且**高估是安全方向**。
* 一长串重复标点被高估最多 5.3 倍（``---------…`` 会被 BPE 合成一个 token，而这里
  按字符数算）。标点的类别内差异没法用线性系数表达，取上沿是唯一不低估的取法。

**两种错的代价完全不对称**：估多了的代价是少注入一条记忆；估少了的代价是请求在
服务端被静默截断，而截断丢的是**最早的消息**——正是人格锚所在的位置。P0 已经踩过
这个坑一次（见计划书 §一的"上下文窗口算大一倍"那一行）。

估出来的值仍然不是上界（最差样本还差 9%），所以装配层另有一道显式的安全余量，
见 :class:`axo.session.budget.TokenBudget`。
"""

from __future__ import annotations

import math

from .text import is_cjk

__all__ = ["ESTIMATOR_VERSION", "UNDER_COUNT_TOLERANCE", "estimate_tokens"]

ESTIMATOR_VERSION = "qwen3-4b/2026-10-r2"
"""估算系数的标定版本。

换分词器（换模型家族）时这个字符串要变，于是"这条记忆占了 184 token"这句话
在账本里是可追溯的：同一个数字在两个版本下不是同一件事。

``r2`` 是分档重标定（数字单独成档、四个系数全部取实测上沿）。r1 的系数在混合
中英文文本上系统性低估，低估意味着预算算大、然后服务端静默截断。
"""

UNDER_COUNT_TOLERANCE = 0.10
"""本估计器对**低估**的承诺上界：任何一段文本的估计值不低于真实值的 90%。

实测最差是 9%（见模块 docstring 的样本表），多留一个百分点是滑量。

**这个常数是有消费者的，不是注释**：装配预算按 ``1/(1−tolerance)`` 反推安全
余量（:class:`axo.session.budget.TokenBudget`），回归测试按它断言。
放在这里而不是各写一份，是因为一旦两处漂开，就会出现"测试说合格、预算却算大了"
这种没人能判对的分歧——而预算算大的后果是服务端静默截断人格锚。

重新标定（``tools/calibrate_tokens.py``）之后，如果实测更差，改这里一处，
余量与断言会一起跟上。"""

#: 按**测量上沿**取值，不是按中位数。理由见模块 docstring 最后一段。
_CJK_PER_CHAR = 0.70
_DIGIT_PER_CHAR = 1.00
_LATIN_PER_CHAR = 0.35
_OTHER_PER_CHAR = 1.00


def estimate_tokens(text: str) -> int:
    """估算一段文本占多少 token。**不含**消息模板的固定开销。

    模板开销由 :class:`axo.session.budget.TokenBudget` 按消息条数另算
    （实测**每条消息** 5 token，整个对话另有 12 的固定底价）——它属于协议层，
    不属于文本本身。把两者混在一个函数里，会让「这段记忆值多少 token」这个
    可核对的问题变成一个不可分解的黑盒。

    **空白不计入。** BPE 分词器会把词前的空格并进那个词自己的 token 里，单独数
    一遍空格等于把它算两次——实测中这是英文文本上最大的一项偏差（1.43 倍）。

    空串返回 0（而不是 1）：空内容在会话逐字稿里是合法状态（被中断的空回复），
    而给它记 1 token 会让「哪些消息不占预算」这类判断失去意义。
    """
    if not text:
        return 0

    cjk = 0
    digit = 0
    latin = 0
    other = 0
    for char in text:
        if char.isspace():
            continue
        # 数字放在最前面：它是系数最高的一档（1.00），被任何别的分支接走都是低估。
        # 它也必须**单独一档**——"一个数字一个 token"和"一个字母 0.35 个 token"
        # 差三倍，混在一起就是旧实现那个 0.45 的样本。
        if char.isdigit():
            digit += 1
        elif is_cjk(char):
            cjk += 1
        elif char.isalnum():
            latin += 1
        else:
            other += 1

    total = (
        cjk * _CJK_PER_CHAR
        + digit * _DIGIT_PER_CHAR
        + latin * _LATIN_PER_CHAR
        + other * _OTHER_PER_CHAR
    )
    return max(1, int(math.ceil(total)))
